const (
	testAPIKey = "TEST-API-KEY-do-not-leak-0123456789"
	toolName   = "fx_series_summary"
)

func TestMain(m *testing.M) {
	code := m.Run()
	testkit.RemoveTemplate()
	os.Exit(code)
}

type testServer struct {
	*paperresultsmcp.Server
	http *httptest.Server
}

func newServer(t *testing.T) (*testServer, *sql.DB) {
	t.Helper()
	path, w := testkit.NewMigratedDB(t)
	s := settings.Default()
	s.Enabled = true
	s.APIKey = testAPIKey
	srv := paperresultsmcp.New(paperresultsmcp.Options{
		Settings: s, DBPath: path, Logger: slog.New(slog.NewJSONHandler(io.Discard, nil)),
		Now: testkit.FixedNow, CapitalJPY: 30_000_000,
	})
	hs := httptest.NewServer(srv.Handler())
	t.Cleanup(func() {
		hs.Close()
		_ = srv.Close()
	})
	return &testServer{Server: srv, http: hs}, w
}

type response struct {
	status int
	body   []byte
}

func (s *testServer) post(t *testing.T, method string, params any) response {
	t.Helper()
	body, _ := json.Marshal(map[string]any{"jsonrpc": "2.0", "id": 1, "method": method, "params": params})
	req, err := http.NewRequest(http.MethodPost, s.http.URL, bytes.NewReader(body))
	if err != nil {
		t.Fatal(err)
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer "+testAPIKey)
	res, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = res.Body.Close() }()
	b, err := io.ReadAll(res.Body)
	if err != nil {
		t.Fatal(err)
	}
	return response{status: res.StatusCode, body: b}
}

func (s *testServer) call(t *testing.T, args map[string]any) response {
	t.Helper()
	return s.post(t, "tools/call", map[string]any{"name": toolName, "arguments": args})
}

// data decodes the successful tool response's structuredContent.data.
func (r response) data(t *testing.T) fxdiag.Data {
	t.Helper()
	if r.status != http.StatusOK {
		t.Fatalf("status %d, body %s", r.status, r.body)
	}
	var env struct {
		Result struct {
			StructuredContent struct {
				Data fxdiag.Data `json:"data"`
			} `json:"structuredContent"`
		} `json:"result"`
	}
	if err := json.Unmarshal(r.body, &env); err != nil {
		t.Fatalf("decode %s: %v", r.body, err)
	}
	return env.Result.StructuredContent.Data
}

func (r response) wantError(t *testing.T, status int, code paperresultsmcp.Code) {
	t.Helper()
	var e struct {
		Code string `json:"code"`
	}
	if err := json.Unmarshal(r.body, &e); err != nil {
		t.Fatalf("decode error body %s: %v", r.body, err)
	}
	if r.status != status || e.Code != string(code) {
		t.Fatalf("want %d %s, got %d %s (%s)", status, code, r.status, e.Code, r.body)
	}
}

// day is the 06:00 JST start of a GMO trading day, in UTC.
func day(date string) time.Time {
	d, err := time.ParseInLocation(time.DateOnly, date, time.FixedZone("JST", 9*3600))
	if err != nil {
		panic(err)
	}
	return d.Add(6 * time.Hour).UTC()
}

// candle inserts the minute `minute` of the trading day: both sides, or only one
// (side "bid" / "ask").
func candle(t *testing.T, w *sql.DB, symbol, date string, minute int, side string) {
	t.Helper()
	at := day(date).Add(time.Duration(minute) * time.Minute)
	px := func(on bool) []any {
		if !on {
			return []any{nil, nil, nil, nil}
		}
		return []any{150.0, 150.1, 149.9, 150.05}
	}
	args := append([]any{symbol, sqlutil.FormatTime(at), date}, px(side != "ask")...)
	args = append(args, px(side != "bid")...)
	testkit.MustExec(t, w, `INSERT INTO research_fx_candles (symbol, open_time, trading_day, bid_open, bid_high, bid_low, bid_close, ask_open, ask_high, ask_low, ask_close, recorded_at)
		VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 't')`, args...)
}

func mark(t *testing.T, w *sql.DB, symbol, date, status string, n int) {
	t.Helper()
	testkit.MustExec(t, w, `INSERT INTO research_fx_days (symbol, trading_day, status, candle_count, fetched_at) VALUES (?, ?, ?, ?, 't')`, symbol, date, status, n)
}

// dump hashes every row of every table, so any write by the tool changes the result.
func dump(t *testing.T, w *sql.DB) map[string]string {
	t.Helper()
	rows, err := w.QueryContext(t.Context(), `SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name`)
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for rows.Next() {
		var n string
		if err := rows.Scan(&n); err != nil {
			t.Fatal(err)
		}
		names = append(names, n)
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	_ = rows.Close()
	out := map[string]string{}
	for _, n := range names {
		r, err := w.QueryContext(t.Context(), `SELECT * FROM "`+n+`"`)
		if err != nil {
			t.Fatal(err)
		}
		cols, _ := r.Columns()
		h := sha256.New()
		for r.Next() {
			vals := make([]any, len(cols))
			ptrs := make([]any, len(cols))
			for i := range vals {
				ptrs[i] = &vals[i]
			}
			if err := r.Scan(ptrs...); err != nil {
				t.Fatal(err)
			}
			_, _ = fmt.Fprintf(h, "%v\n", vals)
		}
		if err := r.Err(); err != nil {
			t.Fatal(err)
		}
		_ = r.Close()
		out[n] = fmt.Sprintf("%x", h.Sum(nil))
	}
	return out
}
